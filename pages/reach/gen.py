    sep = tr.t("sep.list")
    L = []
    w = L.append
    w(tr.t("md.title"))
    w("")
    w(tr.t("md.switch"))
    w("")
    w(tr.t("md.intro"))
    w("")
    w(tr.t("md.page"))
    w(tr.t("md.source"))
    w(tr.t("md.fork"))
    w("")
    w(tr.t("md.fold.h"))
    w("")

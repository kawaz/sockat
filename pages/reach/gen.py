class Tr:
    """1 つの言語の文字列を引く。欠けた文字列は missing に溜める (生成も --check も失敗させる)。"""

    def __init__(self, lang, missing):
        self.lang = lang
        self.missing = missing

    def loc(self, v):
        if isinstance(v, dict) and isinstance(v.get(self.lang), str) and v[self.lang]:
            return v[self.lang]
        self.missing.add(f"{self.lang} の無い表示用の文字列: {json.dumps(v, ensure_ascii=False)}")
        return v.get("ja", "?") if isinstance(v, dict) else str(v)

    def t(self, key, **kw):
        return self.loc(TEXT[key]).format(**kw)



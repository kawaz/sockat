class Model:
    def __init__(self, raw):
        self.raw = raw
        self.params = {k: v["value"] for k, v in raw["params"].items()}
        self.oses = raw["oses"]
        self.os_by_id = {o["id"]: o for o in self.oses}
        self.langs = raw["langs"]
        self.places = raw["places"]
        self.b_order = raw["b_order"]
        self.conditions = raw["conditions"]
        self.cond_by_id = {c["id"]: c for c in self.conditions}
        self.ops = raw["ops"]
        self.routes = raw["routes"]
        self.orders = raw["orders"]
        self.fork = raw["fork"]

    def place_profiles(self, place, os):
        p = self.places[place]
        if "os" in p and os["id"] not in p["os"]:
            return [NO_PLACE]
        if "profiles_by_family" in p:
            by = p["profiles_by_family"]
            return by.get(os["family"], by["*"])
        return p["profiles"]

    def place_len(self, prof, os):
        v = prof.get("len")
        if v == "os.tmp_realpath":
            return len(os["tmp_realpath"])
        return v

    def b_len(self, place, prof, os):
        """B の実パスの長さ。実パスの綴りを使えない B (ソケットのディレクトリ) は None。"""
        n = self.place_len(prof, os)
        if n is None:
            return None
        if prof.get("is_b"):
            return n
        return n + 1 + self.params[self.places[place]["b_name"]]

    def limit(self, name, os):
        if name == "sockaddr":
            return os["sockaddr"]
        return self.params[name]

    def route_in_os(self, r, os):
        if "os" in r and os["id"] not in r["os"]:
            return False
        if "os_attr" in r and not os.get(r["os_attr"]):
            return False
        return True

    def cond_applies(self, cid, op, os):
        c = self.cond_by_id[cid]
        if "ops" in c and op not in c["ops"]:
            return False
        if "os" in c and os["id"] not in c["os"]:
            return False
        if "os_attr" in c and not os.get(c["os_attr"]):
            return False
        return True

    def dims(self, op, os):
        """この操作と OS で値が変わりうる条件の次元と、その値 (id の並び)。"""
        out = {}
        out["lang"] = [l["id"] for l in self.langs]
        out["filename"] = None  # 帯は後で計算する
        order = [self.routes[rid] for rid in self.orders[op] if self.route_in_os(self.routes[rid], os)]
        if self.cond_applies("relpath", op, os) and any(r["spelling"] == "<rel>" for r in order):
            out["relpath"] = None
        for cid in ("thread_cwd", "proc"):
            if self.cond_applies(cid, op, os):
                out[cid] = [True, False]
        if os["bind_follows_symlink"] == "probe" and self.cond_applies("follows", op, os):
            out["follows"] = [True, False]
        for place in PLACE_DIMS:
            if not self.cond_applies(place, op, os):
                continue
            profs = self.place_profiles(place, os)
            if len(profs) > 1:
                out[place] = [p["id"] for p in profs]
        for cid in ("private_tmp", "cross_uid"):
            if self.cond_applies(cid, op, os):
                out[cid] = [True, False]
        return out

    def choose_b(self, op, os, cond):
        """(プロセスの B, usable_cross_uid の B)。どちらも (置き場, profile) か None。"""
        base_id = cond.get("base", "unset")
        if base_id != "unset":
            prof = next(p for p in self.places["base"]["profiles"] if p["id"] == base_id)
            return ("base", prof), (("base", prof) if prof.get("traversable") else None)
        cands = []
        for place in self.b_order:
            profs = self.place_profiles(place, os)
            if place == "sockdir" and op in BIND_OPS:
                pid = self.places["sockdir"]["bind_fixed"]
            else:
                pid = cond.get(place, profs[0]["id"])
            prof = next(p for p in profs if p["id"] == pid)
            if prof.get("usable", True) is not False:
                cands.append((place, prof))
        normal = cands[0] if cands else None
        cross = next((c for c in cands if c[1].get("traversable")), None)
        return normal, cross


def spelling_parts(spelling):
    """綴りの雛形を、決まった長さと、変数 (F・rel・B と params の名前) に分ける。"""
    variables = []
    const_text = TOKEN.sub(lambda m: (variables.append(m.group(1)), "")[1], spelling)
    return len(const_text), variables


def spelling_fixed(model, spelling):
    """綴りのうち、条件によらない長さ (文字と params)。"""
    const, variables = spelling_parts(spelling)
    return const + sum(model.params[v] for v in variables if v in model.params), variables


def spelling_len(model, spelling, env):
    fixed, variables = spelling_fixed(model, spelling)
    return fixed + sum(env[v] for v in variables if v not in model.params)


# ---------- 境目の帯 ----------

def all_routes_for_bands(model, os):
    rs = []
    for op in model.orders:
        for rid in model.orders[op]:
            r = model.routes[rid]
            if model.route_in_os(r, os):
                rs.append(r)
    rs.append(model.fork["bind"])
    fc = dict(model.fork["connect"])
    lb = fc["limit_by_family"]
    fc["limit"] = lb.get(os["family"], lb["*"])
    rs.append(fc)
    return rs


def b_lens(model, os):
    """この OS で B の実パスがとりうる長さ。"""
    lens = set()
    for place in model.places:
        for prof in model.place_profiles(place, os):
            if prof.get("usable", True) is False:
                continue
            n = model.b_len(place, prof, os)
            if n is not None:
                lens.add(n)
    return sorted(lens)


def bands_for(model, os):
    name_max = model.params["name_max"]
    f_cuts, rel_cuts = set(), set()
    for r in all_routes_for_bands(model, os):
        fixed, variables = spelling_fixed(model, r["spelling"])
        limit = model.limit(r["limit"], os)
        if "F" in variables:
            for bl in (b_lens(model, os) if "B" in variables else [0]):
                fmax = limit - fixed - bl
                if 1 <= fmax < name_max:
                    f_cuts.add(fmax)
        if "rel" in variables:
            rel_cuts.add(limit - fixed)
    fb, lo = [], 1
    for cut in sorted(f_cuts):
        fb.append((lo, cut))
        lo = cut + 1
    fb.append((lo, name_max))
    rb, lo = [], 1
    for cut in sorted(rel_cuts):
        rb.append((lo, cut))
        lo = cut + 1
    rb.append((lo, None))
    return fb, rb


def band_id(b):
    lo, hi = b
    return f"{lo}-{hi}" if hi is not None else f"{lo}-"


def band_label(b, tr):
    lo, hi = b
    if hi is None:
        return tr.t("band.open", lo=lo)
    return f"{lo}" if lo == hi else f"{lo}–{hi}"


# ---------- 1 つの組み合わせの計算 (言語によらない形) ----------
#
# 届かない理由は [記号, 数...] で持ち、TEXT の "why.<記号>" で文字列にする。

def requires_ok(model, op, os, cond, token):
    if token == "thread_cwd":
        return bool(os.get("thread_cwd")) and cond.get("thread_cwd", False), ["thread_cwd"]
    if token == "proc":
        return bool(os.get("proc")) and cond.get("proc", False), ["proc"]
    if token == "!proc":
        return not (os.get("proc") and cond.get("proc", False)), None
    if token == "follows_measured":
        return os["bind_follows_symlink"] is True, (["follows_unmeasured"] if os["bind_follows_symlink"] == "probe" else None)
    if token == "follows":
        if op not in BIND_OPS:
            return True, None
        f = os["bind_follows_symlink"]
        if f == "probe":
            return cond["follows"], ["follows"]
        return f, None
    raise ValueError(token)


def try_route(model, op, os, lang, cond, F, rel, r):
    """経路を 1 つ試す。(使えたか, 使えない理由, 通った B)。理由が None なら列に無い (試さない)。"""
    if r["route"] in lang["lacks"]:
        return False, ["lacks"], None
    cross = model.cond_applies("cross_uid", op, os) and cond.get("cross_uid", False)
    normal, cross_b = model.choose_b(op, os, cond)
    env = {"F": F, "rel": rel}
    used = None
    for token in r.get("requires", []):
        if token == "!cross":
            if cross:
                return False, ["cross_skip"], None
        elif token == "B":
            if normal is None:
                return False, ["no_place"], None
            used = normal
        elif token == "Breal":
            b = cross_b if cross else normal
            if b is None:
                return False, (["no_place_cross"] if cross else ["no_place"]), None
            n = model.b_len(b[0], b[1], os)
            if n is None:
                return False, ["sockdir_b"], None
            env["B"] = n
            used = b
        else:
            ok, why = requires_ok(model, op, os, cond, token)
            if not ok:
                return False, why, None
    limit = model.limit(r["limit"], os)
    n = spelling_len(model, r["spelling"], env)
    if n <= limit:
        return True, None, used
    return False, too_long_reason(model, r, limit, env, n), None


def too_long_reason(model, r, limit, env, n):
    _, variables = spelling_parts(r["spelling"])
    if "F" in variables:
        fixed = n - env["F"]
        if limit - fixed < 1:
            return ["place_long", fixed, limit]
        return ["filename", limit - fixed]
    if "rel" in variables:
        return ["rel_both", limit] if r["limit"] == "widened" else ["rel", limit]
    return ["spelling", n, limit]


def route_label(model, r, b):
    """結果の経路の名前。B を通る経路は診断の base を添える。"""
    if not r.get("b"):
        return r["route"]
    if r["b"] == "proc":
        diag = "sockdir" if b[0] == "sockdir" else "proc"
    else:
        diag = model.places[b[0]]["diag"]
    return f"{r['route']} (B: {diag})"


def spelling_of(r, b):
    if r.get("kind") is None:
        return None
    if r["kind"] == "Dangling":
        return {"kind": "Dangling"}
    prof = b[1] if b else {}

    def val(v):
        if isinstance(v, bool):
            return v
        if v == "B.traversable":
            return bool(prof.get("traversable"))
        if v == "not B.under_tmp":
            return not prof.get("under_tmp")
        raise ValueError(v)
    return {"kind": "Linked", "removable": r["removable"], "until": r["until"],
            "usable_cross_uid": val(r["usable_cross_uid"]),
            "usable_with_private_tmp": val(r["usable_with_private_tmp"])}


def peer_view(sp, cond, op):
    if sp["kind"] == "Dangling":
        return ["dangling"]
    problems = []
    if cond.get("cross_uid") and not sp["usable_cross_uid"]:
        problems.append("cross_uid")
    if cond.get("private_tmp") and not sp["usable_with_private_tmp"]:
        problems.append("private_tmp")
    if problems:
        return ["blocked", problems]
    if sp["until"] == "Process":
        return ["process"]
    # 既定の bind は cleanup の口を返さないので、E は D と一緒に OS の掃除で消えるまで残る。
    return ["os_cleanup"] if op == "bind" else ["cleanup"]


def fork_reaches(model, op, os, F):
    if op in BIND_OPS:
        fb = model.fork["bind"]
        return spelling_len(model, fb["spelling"], {"F": F}) <= model.limit(fb["limit"], os)
    fc = model.fork["connect"]
    lb = fc["limit_by_family"]
    limit = model.limit(lb.get(os["family"], lb["*"]), os)
    return spelling_len(model, fc["spelling"], {"F": F}) <= limit


def fork_scenario(model, op, os):
    """fork-cwd の文書の、この操作と OS の場面。fork と比べない操作 (resolve_for_connect) は None。"""
    for s in model.fork["scenarios"]:
        if op in s["ops"] and os["id"] in s["os"]:
            return s["id"]
    return None


def evaluate(model, op, os, lang, cond, F, rel):
    if (model.cond_applies("cross_uid", op, os) and cond.get("cross_uid") and cond.get("base", "unset") != "unset"
            and model.choose_b(op, os, cond)[1] is None):
        return {"reach": False, "why": [[None, "base_eperm"]], "notes": []}
    tried = []
    for rid in model.orders[op]:
        r = model.routes[rid]
        if not model.route_in_os(r, os):
            continue
        ok, why, b = try_route(model, op, os, lang, cond, F, rel, r)
        if ok:
            res = {"reach": True, "route": r["route"], "label": route_label(model, r, b)}
            notes = []
            unc = r.get("unconfirmed")
            if unc and os["id"] in unc["os"]:
                notes.append(unc["note"])
            if op in BIND_OPS:
                sp = spelling_of(r, b)
                res["spelling"] = sp
                res["peer"] = peer_view(sp, cond, op)
            res["notes"] = notes
            return res
        if why is not None:
            tried.append([route_table_label(r)] + why)
    if not tried:
        tried = [[None, "no_route"]]
    res = {"reach": False, "why": tried, "notes": []}
    scenario = fork_scenario(model, op, os)
    if scenario and fork_reaches(model, op, os, F):
        res["fork"] = scenario
    return res


def route_table_label(r):
    """経路の表と届かない理由での経路の名前。B の綴りの形を添える (記号は TEXT の b.<形>)。"""
    return f"{r['route']} ({{b.{r['b']}}})" if r.get("b") else r["route"]


def result_key(res):
    return json.dumps(res, ensure_ascii=False, sort_keys=True)


# ---------- 組み合わせを作って畳む ----------

def enumerate_rows(model, op, os):
    dims = model.dims(op, os)
    fb, rb = bands_for(model, os)
    dims["filename"] = [band_id(b) for b in fb]
    band_of = {band_id(b): b for b in fb}
    if "relpath" in dims:
        dims["relpath"] = [band_id(b) for b in rb]
        band_of.update({band_id(b): b for b in rb})
    names = list(dims)
    lang_by_id = {l["id"]: l for l in model.langs}
    rows = []
    for combo in itertools.product(*(dims[n] for n in names)):
        cond = dict(zip(names, combo))
        flo, fhi = band_of[cond["filename"]]
        corners = [(flo, None), (fhi, None)]
        if "relpath" in cond:
            rlo, rhi = band_of[cond["relpath"]]
            if rhi is not None and rhi < flo:
                continue  # 相対パスはファイル名より短くならない
            rtop = rhi if rhi is not None else 4096
            # ファイル名 ≤ 相対パス の範囲の両端
            corners = [(flo, max(rlo, flo)), (min(fhi, rtop), rtop)]
        lang = lang_by_id[cond["lang"]]
        res = evaluate(model, op, os, lang, cond, *corners[0])
        # 帯の反対の端でも同じ結果になることを確かめる (帯の作り方の誤りを拾う)。
        hi_res = evaluate(model, op, os, lang, cond, *corners[1])
        if result_key(res) != result_key(hi_res):
            raise SystemExit(f"帯の中で結果が変わる: {op} {os['id']} {cond} {res} {hi_res}")
        rows.append(({n: frozenset([cond[n]]) for n in names}, result_key(res)))
    return dims, rows


def fold(dims, rows):
    """畳む。次元を見る順で結果の行数が変わるので、いくつかの順で畳んで一番少ない物を使う。"""
    base = [d for d in DIM_ORDER if d in dims]
    orders = [base, base[::-1], base[-1:] + base[:-1], base[-2:] + base[:-2]]
    best = None
    for order in orders:
        out = fold_in_order(order, rows)
        if best is None or len(out) < len(best):
            best = out
    return best


def fold_in_order(order, rows):
    changed = True
    while changed:
        changed = False
        for d in order:
            groups = {}
            for cond, rk in rows:
                key = (tuple((n, cond[n]) for n in order if n != d), rk)
                groups.setdefault(key, set()).update(cond[d])
            if len(groups) < len(rows):
                changed = True
            new = []
            for (others, rk), vals in groups.items():
                cond = dict(others)
                cond[d] = frozenset(vals)
                new.append((cond, rk))
            rows = new
    return rows


# ---------- 実測の根拠 ----------

def evidence_for(model, op, os, cond, res, fb, rb):
    """行に当たる実測を探す。([場面, 当たった言語 (全部なら None)] の並び, 食い違いの並び)。"""
    refs, mismatches = [], []
    lang_ids = [l["id"] for l in model.langs]
    for ev in model.raw["evidence"]["cases"]:
        if ev["op"] != op or ev["os"] != os["id"]:
            continue
        ok = True
        for d, values in cond.items():
            if d in ("lang", "filename", "relpath"):
                continue
            full = set(model.dims(op, os)[d])
            if d in ev["when"]:
                if ev["when"][d] not in values:
                    ok = False
            elif set(values) != full:
                ok = False
        if not ok:
            continue
        if not any(lo <= ev["filename"] <= hi for lo, hi in (parse_band(b) for b in cond["filename"])):
            continue
        if "relpath" in cond:
            want = ev.get("relpath")
            if want is None:
                if len(cond["relpath"]) != len(rb):
                    continue
                want = 1
            s = os["sockaddr"]
            rng = {"fits-sockaddr": (1, s), "over-sockaddr-within-widened": (s + 1, model.params["widened"])}.get(want, (want, want))
            bands = [parse_band(b) for b in cond["relpath"]]
            if not all(any(lo <= x <= (hi if hi is not None else 10**9) for lo, hi in bands) for x in rng):
                continue
        langs = [l for l in lang_ids if l in cond["lang"]]
        matched = []
        for l in langs:
            obs = ev["observed"].get(l, "")
            if obs is None:
                if not res["reach"]:
                    matched.append(l)
                else:
                    mismatches.append(f"{ev['case']} ({l}): 実測は届かない、計算は {res['label']}")
                continue
            if obs not in {model.routes[rid]["route"] for rid in model.orders[op] if model.routes[rid].get("unchanged")}:
                continue
            if res["reach"] and res["route"] == obs:
                matched.append(l)
            else:
                got = res["label"] if res["reach"] else "届かない"
                mismatches.append(f"{ev['case']} ({l}): 実測は {obs}、計算は {got}")
        if matched:
            refs.append([ev["case"], None if matched == langs else matched])
    return refs, mismatches


def parse_band(bid):
    lo, hi = bid.split("-")
    return int(lo), (int(hi) if hi else None)


